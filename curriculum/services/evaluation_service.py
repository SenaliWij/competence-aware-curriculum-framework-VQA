import torch
import numpy as np
from typing import List, Dict, Any

class EvaluationService:
    """
    Computes and aggregates metrics to assess model competence.
    """
    def __init__(self, history_window: int = 5):
        self.history_window = history_window
        # History is a list of dicts: [{'loss': float, 'accuracy': float}]
        self.history: List[Dict[str, float]] = []

    def compute_accuracy(self, logits: torch.Tensor, labels: torch.Tensor) -> float:
        """
        Computes classification accuracy for a batch.

        Parameters:
            logits:
                Raw model outputs (before softmax).
                Shape: [batch_size, num_classes]

            labels:
                Ground-truth labels.

        Returns:
            Accuracy as a float between 0 and 1.
        """
        if logits.numel() == 0:
            return 0.0
    
        preds = logits.argmax(dim=1)
    
        # Handle legacy one-hot labels if encountered (default: integer labels)
        if labels.dim() == 2:
            labels = labels.argmax(dim=1)
    
        correct = (preds == labels).sum().item()
        return correct / preds.size(0)

    def record_metrics(self, loss: float, accuracy: float):
        """
        Records metrics from one validation step or epoch.

        Parameters:
            loss: validation loss value
            accuracy: validation accuracy value
        """
        self.history.append({'loss': loss, 'accuracy': accuracy})

    def get_moving_average_accuracy(self, window: int = None) -> float:
        """
        Computes moving average accuracy over recent epochs.

        Parameters:
            window:
                Optional override for number of recent epochs to use.
                If None, uses self.history_window.

        Returns:
            Average accuracy over selected window.
        """
        if not self.history:
            return 0.0

        w = window if window else self.history_window
        recent = self.history[-w:]
        accuracies = [h['accuracy'] for h in recent]
        return sum(accuracies) / len(accuracies)

    def is_loss_stable(self, threshold: float = 5e-3, window: int = None) -> bool:
        """
        Determines whether the validation loss has stabilized over recent epochs.

        Checks the overall change (slope) between the first and last loss values in a recent window.

        If the absolute difference between the earliest and latest loss
        in the selected window is < than the given threshold,
        the loss is considered stable.

        Parameters:
            threshold:
                Maximum allowed change in loss across the window.
            window:
                Number of recent epochs to consider.

        Returns:
            True if loss variance < threshold, otherwise False.
        """
        if len(self.history) < 2:
            return False

        w = window if window else self.history_window
        recent = self.history[-w:]
        if len(recent) < 2:
             return False # Not enough data for stability checks

        losses = [h['loss'] for h in recent]
        variance = np.var(losses)
        return variance < threshold

    def get_latest_metrics(self) -> Dict[str, float]:
        """
        Returns the most recent recorded metrics. If no history exists, returns zeros.
        """
        if not self.history:
            return {'loss': 0.0, 'accuracy': 0.0}
        return self.history[-1]

    def reset_history(self):
        """
        Clears all stored metric history.
        """
        self.history = []

